x = 10
print("Initial value of x:" , x)

#Add and Assign (+=)
x = x + 5    #Same as: x += 5
print("After x = x + 5:",x)

#Subtract and Assign (-=)
x = x - 5   #Same as: x -= 5
print("After x = x - 5:",x)

#Multiple and Assign (*=)
x = x * 3  #Same as x *= 3
print("After x = x * 3:",x)

#Divide and Assign (/=)
x = x / 4  #Same as: x /= 4
print("After x = / 4:", x)

