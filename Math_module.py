# Import Math Library
import math
# Math.ceil(x)
x = 10.2
print(math.ceil(x))

# Math.floor(x)
a = 12.5
print(math.floor(a))

# Math.factorial
b = 5
print(math.factorial(b))

# Math.fsum(list/tuple)
l = [10,20,30,40]
print(math.fsum(l))

# Math.sqr(x)
x = 25
print(math.sqrt(x))
print(math.sqrt(81))

# Math.fabs(x)
f = -10
print(math.fabs(f))
